def _rolling_ledger():
    p = os.path.join(OUT_DIR, "oos_ledger_rolling_python_hmm.csv")
    if not os.path.exists(p):
        pytest.skip("run scripts/run_oos_holdout.py first")
    df = pd.read_csv(p)
    for c in ["touched_at", "entry_time", "exit_time", "profit_lock_trigger_ts",
              "profit_lock_activation_ts", "hmm_last_bar_ts"]:
        df[c] = pd.to_datetime(df[c], utc=True, errors="coerce")
    return df


def _pine_ledger():
    p = os.path.join(OUT_DIR, "oos_ledger_frozen_pine_hmm.csv")
    if not os.path.exists(p):
        pytest.skip("run scripts/run_oos_holdout.py first")
    df = pd.read_csv(p)
    for c in ["touched_at", "entry_time", "exit_time"]:
        df[c] = pd.to_datetime(df[c], utc=True, errors="coerce")
    return df


def _executed(df):
    return df[df["skip_reason"].isna()].sort_values("entry_time").reset_index(drop=True)


# 1. No overlapping positions.
def test_no_overlapping_positions():
    d = _executed(_rolling_ledger())
    for i in range(1, len(d)):
        assert d.loc[i, "entry_time"] > d.loc[i - 1, "exit_time"], \
            f"overlap at row {i}: entry {d.loc[i,'entry_time']} <= prior exit {d.loc[i-1,'exit_time']}"


# 2. No same-minute exit and re-entry.
def test_no_same_minute_reentry():
    d = _executed(_rolling_ledger())
    for i in range(1, len(d)):
        assert d.loc[i, "entry_time"] != d.loc[i - 1, "exit_time"]


# 3. No retry after a consumed first touch (each level_id/side appears
# at most once anywhere in the ledger -- one physical touch, ever).
def test_no_retry_after_consumed_touch():
    df = _rolling_ledger()
    dup = df.groupby(["level_id", "side"]).size()
    assert (dup <= 1).all(), f"level_id/side appearing more than once: {dup[dup > 1]}"


# 4. No reserved-year result was calculated before PRE_OOS_LOCK.
# Structural proxy (runs both before and after the lock commit exists):
# the runner script must not import/execute anything at module import time
# that touches reserved-year ledgers, and no reserved-year ledger file may
# already exist in a commit tagged PRE_OOS_LOCK. This test asserts the
# convention: ledger files are gitignored from the PRE_OOS_LOCK commit by
# construction (checked manually at commit time, recorded in the commit
# message); here we simply assert the ledger, if present, is *newer* than
# the runner/engine source files it was produced from (i.e. it was
# generated by running the already-committed code, not hand-edited).
def test_ledger_not_older_than_engine_code():
    p = os.path.join(OUT_DIR, "oos_ledger_rolling_python_hmm.csv")
    if not os.path.exists(p):
        pytest.skip("run scripts/run_oos_holdout.py first")
    engine_mtime = os.path.getmtime(os.path.join(REPO_ROOT, "scripts", "oos_engine.py"))
    ledger_mtime = os.path.getmtime(p)
    assert ledger_mtime >= engine_mtime


# 5. HMM training excludes current and future sessions (trailing_sessions
# only ever returns sessions strictly before the target session).
def test_hmm_training_excludes_current_and_future_sessions():
    from scripts.stage4_regime_data import trailing_sessions
    all_sessions = [f"2020-01-{d:02d}" for d in range(1, 29)]
    for i, sess in enumerate(all_sessions):
        trailing = trailing_sessions(all_sessions, sess, max_sessions=120, min_sessions=1)
        if trailing is None:
            continue
        assert all(s < sess for s in trailing)
        assert sess not in trailing


# 6. Entry state uses only completed five-minute bars (state_before_rich /
# state_before_pine use entry_ts - 5min as the cutoff, never entry_ts itself).
def test_hmm_state_uses_only_completed_bars():
    from scripts.oos_engine import state_before_rich
    idx = pd.date_range("2020-01-02 18:00", periods=10, freq="5min", tz="UTC")
    df = pd.DataFrame({
        "state_label": ["LOW_VOL"] * 10, "max_prob": [0.9] * 10,
        "prob_LOW_VOL": [0.9] * 10, "prob_MID_VOL": [0.05] * 10, "prob_HIGH_VOL": [0.05] * 10,
    }, index=idx)
    cache_probs = {"2020-01-02": df}
    cache_meta = {"2020-01-02": {"n_train_sessions": 20, "earliest_train_session": "x",
                                  "latest_train_session": "y", "param_hash": "h"}}
    # entry exactly at bar idx[5]'s start: idx[5] has NOT completed yet
    # (needs +5min), so the last usable bar is idx[4] (started 5min earlier)
    entry_ts = idx[5]
    r = state_before_rich(cache_probs, cache_meta, "2020-01-02", entry_ts)
    assert r["hmm_last_bar_ts"] == idx[4]
    # entry 1 minute after bar idx[5] completes (idx[5] + 5min): idx[5]
    # itself is now the last usable bar
    entry_ts2 = idx[5] + pd.Timedelta(minutes=6)
    r2 = state_before_rich(cache_probs, cache_meta, "2020-01-02", entry_ts2)
    assert r2["hmm_last_bar_ts"] == idx[5]


# 7 & 8. Profit lock activates exactly one bar after its trigger bar, never
# on the trigger bar itself.
def test_profit_lock_activates_one_bar_after_trigger_never_on_trigger_bar():
    import scripts.stage3_engine as s3
    idx = pd.date_range("2020-01-02 14:30", periods=20, freq="1min", tz="UTC")
    entry = 100.0
    rows = []
    for i, ts in enumerate(idx):
        if i == 0:
            rows.append({"open": entry, "high": entry, "low": entry, "close": entry})
        elif i < 5:
            rows.append({"open": entry, "high": entry + 5, "low": entry - 0.1, "close": entry + 4})
        else:
            rows.append({"open": entry + 4, "high": entry + 4.2, "low": entry + 3.9, "close": entry + 4.1})
    bars = pd.DataFrame(rows, index=idx)
    touch_ts = idx[0]
    cutoff_ts = idx[-1]
    pnl, reason, exit_ts, audit = s3.simulate_exact_r_be(
        bars, touch_ts, cutoff_ts, entry, 1.0, tp_dist=100.0, sl_dist=5.0, trigger_r=0.75, lock_r=0.10)
    assert "trigger_bar_ts" in audit and "trigger_activated_ts" in audit
    trigger_bar_pos = list(idx).index(audit["trigger_bar_ts"])
    activated_pos = list(idx).index(audit["trigger_activated_ts"])
    assert activated_pos == trigger_bar_pos + 1, "activation must be exactly one bar after the trigger bar"


# 9. TP/SL are frozen at entry (never recomputed mid-trade) -- structural
