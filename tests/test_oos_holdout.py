def test_pine_standalone_forward_filter_matches_reference_algorithm():
    """The standalone diag-Gaussian forward filter used for the frozen
    Pine application must be numerically identical to
    scripts.stage4_hmm.causal_forward_filter's algorithm."""
    rng = np.random.default_rng(0)
    n_obs, n_states = 12, 3
    log_probs = rng.normal(size=(n_obs, n_states))
    startprob = np.array([0.9, 0.08, 0.02])
    transmat = np.array([[0.8, 0.15, 0.05], [0.3, 0.5, 0.2], [0.1, 0.2, 0.7]])

    # reference: identical loop logic inlined here from stage4_hmm's algorithm
    probs = np.exp(log_probs - log_probs.max(axis=1, keepdims=True))
    alpha_ref = np.zeros((n_obs, n_states))
    a = startprob * probs[0]
    a = a / a.sum()
    alpha_ref[0] = a
    for t in range(1, n_obs):
        a = (alpha_ref[t - 1] @ transmat) * probs[t]
        a = a / a.sum()
        alpha_ref[t] = a

    alpha_test = _forward_filter_from_loglik(log_probs, startprob, transmat)
    assert np.allclose(alpha_ref, alpha_test)


